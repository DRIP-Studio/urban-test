import { expect, test } from '@playwright/test';
import { resolve } from 'node:path';
import { API, createProject } from './helpers';
test('production bundle exports an offline presentation with its compiled graphic compositor',async({page,request})=>{
  const pid=await createProject(request,'Production story QA'),errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${API}/#/p/${pid}`);
  await expect(page.locator('.topbar').getByText('Production story QA',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>Boolean((window as any).__drip))).toBe(false);
  await page.getByRole('button',{name:'Presenta',exact:true}).click();
  await page.getByRole('button',{name:"Aggiungi scena dall'inquadratura",exact:true}).click();
  await page.getByRole('button',{name:'Modifica scena 1',exact:true}).click();
  await page.getByRole('button',{name:'Aggiungi testo',exact:true}).click();
  await expect(page.getByText('Testo di progetto · text',{exact:true})).toBeVisible();
  await page.evaluate(()=>{const w=window as any;w.__exportProbe=[];const create=URL.createObjectURL;URL.createObjectURL=(blob:Blob|MediaSource)=>{w.__exportProbe.push({kind:'blob',type:blob instanceof Blob?blob.type:'media',size:blob instanceof Blob?blob.size:0});return create.call(URL,blob);};document.addEventListener('click',e=>{const button=(e.target as Element)?.closest('button');if(button?.textContent?.includes('Esporta presentazione interattiva HTML'))w.__exportProbe.push({kind:'click',disabled:button.disabled});},true);});
  const download=page.waitForEvent('download',{timeout:30000});
  await page.getByRole('button',{name:'Esporta presentazione interattiva HTML',exact:true}).click();
  await (await download.catch(async(error)=>{console.log('Production export diagnostic',await page.evaluate(()=>(window as any).__exportProbe),errors);throw error;})).saveAs('.shots/production-presentation.html');
  await page.waitForTimeout(1200);
  const link=page.getByRole('link',{name:'Scarica HTML pronto',exact:true});await expect(link).toBeVisible();expect(await link.evaluate(async(a:HTMLAnchorElement)=>(await fetch(a.href)).ok)).toBe(true);
  await page.goto('file:///'+resolve('.shots/production-presentation.html').replace(/\\/g,'/'));
  await expect(page.getByText('Production story QA',{exact:true})).toBeVisible();
  const camera=await page.evaluate('data.document.scenes[0].camera');expect(camera.center).toHaveLength(2);expect(camera.center.every(Number.isFinite)).toBe(true);expect(camera.zoom).toBeGreaterThan(0);
  await page.locator('#scenes button').first().click();
  await page.waitForFunction(()=>{const c=document.querySelector('canvas')!;const g=c.getContext('2d')!;return g.getImageData(0,0,c.width,c.height).data.some((v,i)=>i%4===3&&v>0);});
  await page.screenshot({path:'.shots/production-presentation.png',fullPage:true});
  await page.emulateMedia({media:'print'});await page.waitForTimeout(300);
  await page.pdf({path:'.shots/production-presentation.pdf',preferCSSPageSize:true,printBackground:true});
  expect(errors).toEqual([]);
});
